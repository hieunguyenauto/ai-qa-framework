#!/usr/bin/env python3
"""Build manager/GUIDE.md from the source files. Never edit GUIDE.md by hand.
Usage: python3 manager/scripts/build_guide.py          # regenerate GUIDE.md
       python3 manager/scripts/build_guide.py --check  # exit 1 if GUIDE.md is out of date
"""
import pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCES = [
    ("General rules for the AI", ["CLAUDE.md"]),
    ("Skills", sorted(p.relative_to(ROOT).as_posix() for p in (ROOT / ".claude/skills").rglob("*.md"))),
    ("Templates", sorted(p.relative_to(ROOT).as_posix() for d in ("qc/templates", "automation/templates", "manager/templates") for p in (ROOT / d).glob("*.md"))),
    ("Lessons promoted to rules", ["qc/lessons/INDEX.md", "automation/lessons/INDEX.md"]),
    ("Decisions", ["manager/decisions.md"]),
]

def read(rel):
    p = ROOT / rel
    return p.read_text(encoding="utf8").replace("\r\n", "\n").rstrip() if p.exists() else "(file missing)"

def build():
    version = read("manager/VERSION")
    out = [
        f"<!-- GENERATED by manager/scripts/build_guide.py — edit the source files and run it again. Version {version} -->",
        read("manager/handbook.md"),
        "",
        f"## Appendix A — Current sources (v{version}, generated)",
    ]
    for title, files in SOURCES:
        out.append(f"\n### {title}")
        for rel in files:
            out += [f"\n#### `{rel}`", "", "~~~~markdown", read(rel), "~~~~"]
    log = read("manager/CHANGELOG.md").splitlines()
    out += ["", "## Appendix B — Recent changes", "", *log[:60], ""]
    return "\n".join(out)

if __name__ == "__main__":
    text = build()
    target = ROOT / "manager/GUIDE.md"
    if "--check" in sys.argv:
        old = target.read_text(encoding="utf8").replace("\r\n", "\n") if target.exists() else ""
        if old != text:
            print("GUIDE.md is out of date. Run: python3 manager/scripts/build_guide.py && git add manager/GUIDE.md")
            sys.exit(1)
        sys.exit(0)
    target.write_bytes(text.encode("utf8"))
    print(f"GUIDE.md generated ({len(text):,} characters)")
